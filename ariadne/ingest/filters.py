"""Decide which repository files are indexed.

Two layers:
  * `path_decision` — cheap checks on the path alone (extension, vendor/build
    directories, lockfiles, generated or secret-looking names).
  * `content_decision` — checks on the bytes (size, binary, minified,
    generated markers, embedded secrets).

A skipped file is reported with a reason only; secret matches are never
echoed back.
"""

from __future__ import annotations

import re
from pathlib import PurePosixPath
from typing import Optional

LANGUAGE_BY_EXT = {
    ".py": "python",
    ".js": "javascript",
    ".jsx": "javascript",
    ".mjs": "javascript",
    ".cjs": "javascript",
    ".ts": "typescript",
    ".tsx": "tsx",
}

IGNORED_DIRS = {
    ".git", ".hg", ".svn", "node_modules", "bower_components", "jspm_packages",
    "vendor", "vendors", "third_party", "third-party", "external",
    "dist", "build", "out", "target", "bin", "obj", "lib-cov", "coverage",
    "__pycache__", ".venv", "venv", "env", ".env", "site-packages", ".tox",
    ".nox", ".mypy_cache", ".pytest_cache", ".ruff_cache", ".eggs",
    ".next", ".nuxt", ".svelte-kit", ".output", ".turbo", ".cache", ".parcel-cache",
    ".idea", ".vscode", ".gradle", ".terraform", "migrations_generated",
}

SECRET_NAME = re.compile(
    r"(^|[._-])(secret|secrets|credential|credentials|private[._-]?key|apikeys?|"
    r"api[._-]keys?)([._-]|$)",
    re.IGNORECASE,
)

GENERATED_NAME = re.compile(
    r"(\.min\.(js|mjs|cjs)$|\.bundle\.js$|\.chunk\.js$|-bundle\.js$|_pb2(_grpc)?\.py$|"
    r"\.pb\.(js|ts)$|\.generated\.(js|ts|py)$|\.d\.ts$)",
    re.IGNORECASE,
)

GENERATED_MARKER = re.compile(
    rb"(@generated|do not edit|auto-generated|autogenerated|generated by|code generated)",
    re.IGNORECASE,
)

# High-confidence credential patterns. Matching a file excludes it entirely.
SECRET_PATTERNS = [
    re.compile(rb"-----BEGIN (?:RSA |EC |DSA |OPENSSH |PGP |ENCRYPTED )?PRIVATE KEY-----"),
    re.compile(rb"\bAKIA[0-9A-Z]{16}\b"),                          # AWS access key id
    re.compile(rb"\bASIA[0-9A-Z]{16}\b"),
    re.compile(rb"\bgh[pousr]_[A-Za-z0-9]{36,}\b"),                 # GitHub tokens
    re.compile(rb"\bgithub_pat_[A-Za-z0-9_]{60,}\b"),
    re.compile(rb"\bxox[abprs]-[A-Za-z0-9-]{10,}\b"),              # Slack
    re.compile(rb"\bAIza[0-9A-Za-z_-]{35}\b"),                      # Google API key
    re.compile(rb"\bsk_live_[0-9A-Za-z]{20,}\b"),                   # Stripe live key
    re.compile(rb"\bsk-(?:proj-)?[A-Za-z0-9_-]{32,}\b"),            # common LLM-style keys
    re.compile(rb"\bLLM_\d{6,}_[A-Za-z0-9]{16,}\b"),               # Meta Model API keys
    re.compile(rb"(?i)\b(?:password|passwd|secret|api_key|apikey|access_token)\s*[:=]\s*['\"][^'\"\s]{12,}['\"]"),
]


def language_for(path: str) -> Optional[str]:
    return LANGUAGE_BY_EXT.get(PurePosixPath(path).suffix.lower())


def normalize_path(path: str) -> Optional[str]:
    """Return a safe repo-relative POSIX path, or None if it escapes the root."""
    p = path.replace("\\", "/")
    if p.startswith("/") or re.match(r"^[A-Za-z]:", p):
        return None
    parts = [s for s in p.split("/") if s not in ("", ".")]
    if not parts or any(s == ".." for s in parts):
        return None
    return "/".join(parts)


def path_decision(path: str) -> Optional[str]:
    """Return a skip reason, or None if the path is indexable."""
    pp = PurePosixPath(path)
    if language_for(path) is None:
        return "unsupported"
    for part in pp.parts[:-1]:
        low = part.lower()
        if low in IGNORED_DIRS or low.endswith(".egg-info"):
            return "ignored_dir"
    name = pp.name
    if name.startswith(".env"):
        return "secret_name"
    if GENERATED_NAME.search(name):
        return "generated"
    stem = name.rsplit(".", 1)[0]
    if SECRET_NAME.search(stem):
        return "secret_name"
    return None


def content_decision(data: bytes, max_bytes: int) -> Optional[str]:
    if len(data) > max_bytes:
        return "too_large"
    if not data.strip():
        return "empty"
    if b"\x00" in data[:8192]:
        return "binary"
    head = data[:1024]
    if GENERATED_MARKER.search(head):
        return "generated"
    lines = data.count(b"\n") + 1
    if len(data) > 5000 and len(data) / lines > 300:
        return "minified"
    for pat in SECRET_PATTERNS:
        if pat.search(data):
            return "possible_secret"
    return None
