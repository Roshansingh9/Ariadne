import os

import pytest

from ariadne.ingest.fetch import Limits, walk_directory
from ariadne.ingest.filters import content_decision, normalize_path, path_decision

# Assembled at runtime so no credential-shaped literal is committed.
FAKE_AWS = "AKIA" + "IOSFODNN7" + "EXAMPLE"
FAKE_GH = "ghp_" + "a1B2" * 9
FAKE_KEY_HEADER = "-----BEGIN " + "RSA PRIVATE KEY-----"


@pytest.mark.parametrize("path,reason", [
    ("src/app.py", None),
    ("web/app.tsx", None),
    ("lib/util.mjs", None),
    ("README.md", "unsupported"),
    ("image.png", "unsupported"),
    ("node_modules/react/index.js", "ignored_dir"),
    ("pkg/node_modules/x/y.js", "ignored_dir"),
    (".venv/lib/site.py", "ignored_dir"),
    ("build/out.js", "ignored_dir"),
    ("dist/index.js", "ignored_dir"),
    ("vendor/lib.py", "ignored_dir"),
    ("foo.egg-info/x.py", "ignored_dir"),
    ("static/app.min.js", "generated"),
    ("proto/user_pb2.py", "generated"),
    ("types/index.d.ts", "generated"),
    ("config/secrets.py", "secret_name"),
    ("credentials.js", "secret_name"),
    ("aws_credentials.py", "secret_name"),
    ("src/token.py", None),                        # legitimate name, not a secret file
    ("auth/password_reset.py", None),
    (".env.js", "secret_name"),
])
def test_path_decision(path, reason):
    assert path_decision(path) == reason


@pytest.mark.parametrize("raw,expected", [
    ("a/b.py", "a/b.py"), ("./a//b.py", "a/b.py"), ("a\\b.py", "a/b.py"),
    ("../x.py", None), ("a/../../x.py", None), ("/etc/passwd", None), ("C:/x.py", None),
])
def test_normalize_path(raw, expected):
    assert normalize_path(raw) == expected


def test_content_decisions():
    lim = 1000
    assert content_decision(b"def f():\n    return 1\n", lim) is None
    assert content_decision(b"x" * 2000, lim) == "too_large"
    assert content_decision(b"   \n", lim) == "empty"
    assert content_decision(b"abc\x00def", lim) == "binary"
    assert content_decision(b"# @generated by protoc\nx=1\n", lim) == "generated"
    assert content_decision(b"// Code generated by tool. DO NOT EDIT.\n", lim) == "generated"
    assert content_decision(("var a=1;" * 900).encode(), 10_000) == "minified"
    assert content_decision(f"KEY = '{FAKE_AWS}'\n".encode(), lim) == "possible_secret"
    assert content_decision(f"t = '{FAKE_GH}'\n".encode(), lim) == "possible_secret"
    assert content_decision(f"{FAKE_KEY_HEADER}\nabc\n".encode(), lim) == "possible_secret"
    assert content_decision(b"password = 'hunter2hunter2hunter2'\n", lim) == "possible_secret"
    assert content_decision(b"password = os.environ['PW']\n", lim) is None


def test_walk_directory_filters_and_reports(tmp_path):
    (tmp_path / "app").mkdir()
    (tmp_path / "app" / "main.py").write_text("def main():\n    pass\n")
    (tmp_path / "app" / "leak.py").write_text(f"KEY = '{FAKE_AWS}'\n")
    (tmp_path / "node_modules" / "x").mkdir(parents=True)
    (tmp_path / "node_modules" / "x" / "i.js").write_text("module.exports = 1;\n")
    (tmp_path / ".env").write_text("SECRET=1\n")
    (tmp_path / "notes.md").write_text("# hi\n")
    (tmp_path / "big.py").write_text("x = 1\n" * 50_000)

    res = walk_directory(str(tmp_path), Limits(max_file_bytes=64 * 1024))
    paths = [p for p, _ in res.files]
    assert paths == ["app/main.py"]
    assert res.skipped.get("possible_secret") == 1
    assert res.skipped.get("too_large") == 1
    # node_modules is pruned before descending, so it is never even listed
    assert not any("node_modules" in s["path"] for s in res.skipped_samples)
    # secret matches are never echoed — only path + reason
    assert all(set(s) == {"path", "reason"} for s in res.skipped_samples)


def test_walk_directory_does_not_follow_symlinks(tmp_path):
    outside = tmp_path / "outside"
    outside.mkdir()
    (outside / "secret_impl.py").write_text("def stolen():\n    pass\n")
    repo = tmp_path / "repo"
    repo.mkdir()
    (repo / "ok.py").write_text("def ok():\n    pass\n")
    try:
        os.symlink(outside / "secret_impl.py", repo / "link.py")
        os.symlink(outside, repo / "linkdir", target_is_directory=True)
    except (OSError, NotImplementedError):
        pytest.skip("symlinks not permitted on this platform")
    res = walk_directory(str(repo), Limits())
    assert [p for p, _ in res.files] == ["ok.py"]


def test_file_limit_truncates(tmp_path):
    for i in range(5):
        (tmp_path / f"m{i}.py").write_text(f"def f{i}():\n    pass\n")
    res = walk_directory(str(tmp_path), Limits(max_files=3))
    assert len(res.files) == 3 and res.truncated
    assert res.skipped["limit_reached"] == 2
